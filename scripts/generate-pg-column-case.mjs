#!/usr/bin/env node
/**
 * Generates the folded-name -> camelCase map from the mixed-case column
 * declarations in postgres_schema.sql.
 *
 * Postgres folds unquoted identifiers to lowercase on the way in, so a column
 * declared as `actorName` comes back on reads as `actorname`. src/lib/db.ts
 * restores the intended casing from a map that used to be hand-curated, and it
 * silently missed five schema columns, which crashed the admin audit-log filter.
 * The map is now derived from the schema, so a new mixed-case column cannot be
 * forgotten again.
 *
 * Names the schema file cannot account for are pinned by hand instead; see
 * HAND_MAP_ENTRIES.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA = join(ROOT, "postgres_schema.sql");
const OUT = join(ROOT, "src", "lib", "pgColumnCase.generated.ts");

/** PL/pgSQL words that the declaration regex can mistake for a column name. */
const SQL_KEYWORDS = new Set([
  "BEGIN", "END", "IF", "ELSE", "ELSIF", "THEN", "LOOP", "FOREACH", "RETURN",
  "RAISE", "NOTICE", "EXCEPTION", "UNIQUE", "NOW", "VARCHAR", "TEXT", "INTEGER",
]);

/**
 * Folded names that no mixed-case column in postgres_schema.sql can produce, so
 * the generator cannot derive them. They look like SQLite-era camelCase columns
 * (`notifications.isRead` vs today's `is_read`) and the app already reads the
 * snake_case forms, which means they are probably inert. Kept because a column
 * that exists only in the live DB cannot be ruled out from the repo; delete them
 * once an information_schema check confirms none of these names is real.
 */
const HAND_MAP_ENTRIES = [
  ["isread", "isRead"],
  ["userid", "userId"],
  ["taskname", "taskName"],
  ["taskpdfurl", "taskPdfUrl"],
  ["submissionurl", "submissionUrl"],
  ["vivaassessment", "vivaAssessment"],
  ["camid", "camId"],
  ["camname", "camName"],
  ["coveredsubject", "coveredSubject"]
];

function schemaColumns() {
  const ddl = readFileSync(SCHEMA, "utf8");
  const found = new Map();
  for (const line of ddl.split("\n")) {
    const match = line.match(/^\s+([a-z][a-z_]*[A-Z][A-Za-z0-9]*)\s+[A-Za-z]/);
    if (!match) continue;
    const col = match[1];
    if (SQL_KEYWORDS.has(col.toUpperCase())) continue;
    found.set(col.toLowerCase(), col);
  }
  return found;
}

function render(schemaMap) {
  const merged = new Map([...schemaMap, ...HAND_MAP_ENTRIES]);
  const lines = [...merged.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([folded, camel]) => `  ["${folded}", "${camel}"],`);
  const schemaCount = schemaMap.size;
  return `// GENERATED by scripts/generate-pg-column-case.mjs — do not edit the schema rows.\n` +
    `// Re-run with: npm run db:column-case\n` +
    `// Covers every mixed-case column in postgres_schema.sql (${schemaCount})\n` +
    `// plus the handful of folded names the schema file cannot account for.\n` +
    `export const PG_COLUMN_CASE_ENTRIES: [string, string][] = [\n${lines.join("\n")}\n];\n` +
    `export const PG_SCHEMA_COLUMN_COUNT = ${schemaCount};\n`;
}

if (!existsSync(SCHEMA)) {
  console.error(`[column-case] ${SCHEMA} not found — cannot generate the casing map.`);
  process.exit(1);
}

const schemaMap = schemaColumns();
if (schemaMap.size < 20) {
  // A collapsed parse would quietly shrink the map and re-introduce the original bug.
  console.error(`[column-case] only found ${schemaMap.size} mixed-case columns in the schema; refusing to write.`);
  process.exit(1);
}

const next = render(schemaMap);
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
if (current === next) {
  console.log(`[column-case] up to date (${schemaMap.size} schema columns).`);
} else {
  writeFileSync(OUT, next, "utf8");
  console.log(`[column-case] wrote ${schemaMap.size} schema columns + ${HAND_MAP_ENTRIES.length} pinned names to src/lib/pgColumnCase.generated.ts`);
}
